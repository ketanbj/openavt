"""Generate paper macros from the committed local QUIC evidence, without rerunning experiments."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "docs/quic-verification.json"
DESTINATION = ROOT / "paper/artifacts/measurements.tex"


def main():
    evidence = json.loads(SOURCE.read_text())
    rows = []
    for scenario in evidence["sdk_scenarios"]:
        assert scenario["verified"]
        assert scenario["business"]["gateway"] == {
            "requests": 8,
            "handler_executions": 1,
            "denials": 7,
        }
        assert all(result["verified"] for result in scenario["caller"]["results"])
        for role in ("caller", "business"):
            assert scenario[role]["sdk"]["state"] == "verified"
            assert scenario[role]["sdk"]["error"] is None
        profile = scenario["profile"].upper().replace("VOICEBAND", "FSK")
        route = "WebRTC" if scenario["transport"] == "webrtc" else "Provider"
        faults = "Fixed" if scenario["audio_fault_injection"] else "None"
        elapsed = scenario["caller"]["sdk"]["handshake_wall_seconds"]
        rows.append(f"{route} {profile} & {faults} & {elapsed:.3f} & 1 \\\\")
    assert len(rows) == 4
    content = (
        "% Generated by paper/scripts/extract_results.py from docs/quic-verification.json.\n"
        "\\newcommand{\\implementationcommit}{\\code{033f8bf}}\n"
        f"\\newcommand{{\\testcount}}{{{evidence['test_suite']['passed']}}}\n"
        "\\newcommand{\\measurementrows}{%\n" + "\n".join(rows) + "\n}\n"
    )
    DESTINATION.parent.mkdir(exist_ok=True)
    DESTINATION.write_text(content)
    print(f"Generated {len(rows)} single-call observations from {SOURCE.name}")


if __name__ == "__main__":
    main()
